-- ============================================================================
-- V1: the schema as it stands before Flyway took over.
--
-- This reproduces exactly what Hibernate's ddl-auto=update had created, so a
-- brand-new database ends up identical to an existing one. Databases that
-- already contain these tables are baselined at version 1 and skip this file
-- (spring.flyway.baseline-on-migrate / baseline-version), so nothing here
-- runs against live data.
--
-- Deliberately unchanged from the original, including the weaknesses that V2
-- goes on to fix: money held as double precision, no foreign keys, no
-- indexes, and a nullable user_id.
-- ============================================================================

CREATE TABLE IF NOT EXISTS users (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    apmc_location varchar(255),
    business_name varchar(255),
    created_at    timestamp(6),
    mobile        varchar(255) NOT NULL UNIQUE,
    name          varchar(255) NOT NULL,
    password      varchar(255) NOT NULL,
    role          varchar(255) NOT NULL
);

CREATE TABLE IF NOT EXISTS business_profile (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    address         varchar(255) NOT NULL,
    business_name   varchar(255) NOT NULL,
    gstin           varchar(255),
    mandi_license   varchar(255),
    proprietor_name varchar(255) NOT NULL,
    signature_data  text,
    signature_name  varchar(255),
    signature_type  varchar(255),
    tagline         varchar(255),
    updated_at      timestamp(6),
    upi_id          varchar(255),
    user_id         bigint
);

CREATE TABLE IF NOT EXISTS commodities (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    default_rate double precision NOT NULL,
    name         varchar(255) NOT NULL,
    user_id      bigint
);

CREATE TABLE IF NOT EXISTS farmers (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at          timestamp(6),
    mobile              varchar(255),
    name                varchar(255) NOT NULL,
    outstanding_balance double precision,
    user_id             bigint,
    village             varchar(255)
);

CREATE TABLE IF NOT EXISTS purchases (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    advance_paid     double precision NOT NULL,
    created_at       timestamp(6),
    date             varchar(255) NOT NULL,
    farmer_id        bigint NOT NULL,
    purchase_number  varchar(255) NOT NULL,
    remaining_amount double precision NOT NULL,
    status           varchar(255) NOT NULL,
    total_amount     double precision NOT NULL,
    user_id          bigint
);

CREATE TABLE IF NOT EXISTS purchase_items (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    amount       double precision NOT NULL,
    commodity_id bigint NOT NULL,
    purchase_id  bigint NOT NULL,
    quantity     double precision NOT NULL,
    rate         double precision NOT NULL,
    user_id      bigint
);

CREATE TABLE IF NOT EXISTS payments (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    amount       double precision NOT NULL,
    created_at   timestamp(6),
    payment_date varchar(255) NOT NULL,
    payment_mode varchar(255) NOT NULL,
    purchase_id  bigint NOT NULL,
    user_id      bigint
);

CREATE TABLE IF NOT EXISTS mandi_sales (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bags            integer,
    buyer_location  varchar(255),
    buyer_mobile    varchar(255),
    buyer_name      varchar(255) NOT NULL,
    commodity_id    bigint NOT NULL,
    created_at      timestamp(6),
    date            varchar(255) NOT NULL,
    hamali          double precision,
    mandi_cess      double precision,
    net_amount      double precision NOT NULL,
    notes           text,
    payment_mode    varchar(255) NOT NULL,
    payment_status  varchar(255) NOT NULL,
    sale_number     varchar(255) NOT NULL,
    sale_rate       double precision NOT NULL,
    subtotal        double precision NOT NULL,
    transport       double precision,
    user_id         bigint,
    vehicle_number  varchar(255),
    weight_quintals double precision NOT NULL
);

CREATE TABLE IF NOT EXISTS stock_adjustments (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bags            integer,
    commodity_id    bigint NOT NULL,
    created_at      timestamp(6),
    date            varchar(255) NOT NULL,
    rate            double precision,
    reason          varchar(255) NOT NULL,
    type            varchar(255) NOT NULL,
    user_id         bigint,
    weight_quintals double precision NOT NULL
);
